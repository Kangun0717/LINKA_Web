/**
 * Nationality options, stored as ISO 3166-1 alpha-2 codes.
 *
 * Only the code goes into `profiles.nationality`; the flag and the English
 * name are presentation, derived at render time. That keeps the stored value
 * stable if we ever localise the labels.
 */
export type Country = {
  code: string
  name: string
}

/** `JP` → 🇯🇵, by mapping each letter to its regional indicator symbol. */
export function flagOf(code: string): string {
  return code
    .toUpperCase()
    .split('')
    .map((letter) => String.fromCodePoint(0x1f1e6 + letter.charCodeAt(0) - 65))
    .join('')
}

